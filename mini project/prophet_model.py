from prophet import Prophet
import pandas as pd
def train_prophet(df):
    data = df.reset_index()
    data = data.rename(columns={
        "service_date": "ds",
        "total_rides": "y"
    })
    model = Prophet()
    model.fit(data)
    return model

import pandas as pd
df = pd.read_csv("cta_ridership.csv")
df["service_date"] = pd.to_datetime(df["service_date"], format='mixed')
df["total_rides"] = df["total_rides"].astype(str).str.replace(",", "").astype(int)
df = df[["service_date","total_rides"]]
model = train_prophet(df)
future = model.make_future_dataframe(periods=30)
forecast = model.predict(future)
print(forecast[["ds","yhat"]].tail())



import matplotlib.pyplot as plt

fig = model.plot(forecast)
plt.title("CTA Ridership Forecast")
plt.xlabel("Date")
plt.ylabel("Total Rides")
plt.show()

# Save the dataframe to your current project folder
forecast.to_csv("predictions_1.csv", index=False)

